#!/usr/bin/env python3
"""Project configuration shared by the typeface-prototyping scripts. Stdlib only.

A project is a directory (the `--root`, default: the current working directory) that holds
    docs/PRD.md            the font PRD (its H1 is "<Family> — Product Requirements Document")
    font.json              optional; see font.example.json next to this file
    specimen/              generated: glyphs.json, index.html, tester.html
    fonts/                 generated by build_font.py

Resolution order for every field: font.json, then the PRD, then the defaults below.
    family      font.json "family"      | PRD H1 text before " — " / " - "          | "Untitled"
    owner       font.json "owner"       | PRD header table row "| Owner | ... |"    | ""
    version     font.json "version"     | PRD header table row "| Version | ... |"  | ""
    classification  font.json           | PRD header table row "| Classification |" | ""
    weights     font.json "weights" {name: stem} | PRD section "Weights and axes" table rows
                whose first cell is a known style name (stem = "Vertical stem" column)
                                                                               | Light 62, Medium 108, Bold 158
    default     font.json "default"     | "Medium" if present, else the middle weight
    vendor      font.json "vendor"      | "UKWN" (4-char OpenType vendor id)

Weight names must be standard style names so that CSS weights follow: Thin 100, ExtraLight 200,
Light 300, Regular 400, Medium 500, SemiBold 600, Bold 700, ExtraBold 800, Black 900.
"""
import argparse
import json
import os
import re

CSS_WEIGHTS = {"Thin": 100, "ExtraLight": 200, "Light": 300, "Regular": 400, "Medium": 500,
               "SemiBold": 600, "Bold": 700, "ExtraBold": 800, "Black": 900}
DEFAULT_WEIGHTS = {"Light": 62, "Medium": 108, "Bold": 158}


def add_root_arg(parser):
    parser.add_argument("--root", default=os.getcwd(),
                        help="project root holding docs/PRD.md and optionally font.json (default: cwd)")
    return parser


def root_parser(doc):
    return add_root_arg(argparse.ArgumentParser(description=(doc or "").strip().splitlines()[0]))


def _prd_fields(prd_text):
    out = {}
    m = re.search(r"^#\s+(.+?)\s*$", prd_text, re.M)
    if m:
        out["family"] = re.split(r"\s+[—–-]\s+", m.group(1))[0].strip()
    for key in ("Owner", "Version", "Classification"):
        m = re.search(r"^\|\s*%s\s*\|\s*(.+?)\s*\|\s*$" % key, prd_text, re.M)
        if m:
            out[key.lower()] = m.group(1)
    # weights table: a row per instance, first cell the style name, "Vertical stem" column the stem
    sec = re.search(r"^##\s+\d*\.?\s*Weights and axes\s*$(.*?)(?=^##\s|\Z)", prd_text, re.M | re.S)
    if sec:
        rows = [[c.strip() for c in ln.strip().strip("|").split("|")]
                for ln in sec.group(1).splitlines() if ln.strip().startswith("|")]
        if rows:
            header = [h.lower() for h in rows[0]]
            col = next((i for i, h in enumerate(header) if "stem" in h), None)
            weights = {}
            for r in rows[1:]:
                name = re.sub(r"\s*\(.*\)\s*", "", r[0]).strip()
                if col is not None and name in CSS_WEIGHTS and len(r) > col:
                    try:
                        weights[name] = int(re.sub(r"[^\d]", "", r[col]))
                    except ValueError:
                        pass
            if weights:
                out["weights"] = weights
    return out


def load_project(root):
    root = os.path.abspath(root)
    cfg = {}
    fj = os.path.join(root, "font.json")
    if os.path.exists(fj):
        with open(fj, encoding="utf-8") as f:
            cfg = json.load(f)
    prd_path = os.path.join(root, "docs", "PRD.md")
    prd = {}
    if os.path.exists(prd_path):
        with open(prd_path, encoding="utf-8") as f:
            prd = _prd_fields(f.read())
    weights = cfg.get("weights") or prd.get("weights") or dict(DEFAULT_WEIGHTS)
    bad = [w for w in weights if w not in CSS_WEIGHTS]
    if bad:
        raise SystemExit("font.json weights must use standard style names %s; got %s"
                         % (sorted(CSS_WEIGHTS, key=CSS_WEIGHTS.get), bad))
    weights = dict(sorted(weights.items(), key=lambda kv: kv[1]))
    names = list(weights)
    default = cfg.get("default") or ("Medium" if "Medium" in weights else names[len(names) // 2])
    if default not in weights:
        raise SystemExit("font.json default weight %r is not one of %s" % (default, names))
    return {
        "root": root,
        "family": cfg.get("family") or prd.get("family") or "Untitled",
        "owner": cfg.get("owner") or prd.get("owner", ""),
        "version": cfg.get("version") or prd.get("version", ""),
        "classification": cfg.get("classification") or prd.get("classification", ""),
        "weights": weights,
        "css_weights": {n: CSS_WEIGHTS[n] for n in weights},
        "default": default,
        "vendor": (cfg.get("vendor") or "UKWN")[:4].ljust(4),
        "vmetrics": {"ascender": int((cfg.get("metrics") or {}).get("ascender", 950)),
                     "descender": int((cfg.get("metrics") or {}).get("descender", -250))},
        "prd": prd_path,
        "glyphs_json": os.path.join(root, "specimen", "glyphs.json"),
        "specimen": os.path.join(root, "specimen", "index.html"),
        "tester": os.path.join(root, "specimen", "tester.html"),
        "fonts_dir": os.path.join(root, "fonts"),
    }


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


if __name__ == "__main__":
    args = root_parser(__doc__).parse_args()
    print(json.dumps(load_project(args.root), indent=2))
